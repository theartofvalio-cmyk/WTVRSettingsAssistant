    internal static bool TryGet(string languageCode, string key, out string? value)
    {
        value = null;
        if (Packs.TryGetValue(languageCode, out Dictionary<string, string>? pack) && pack.TryGetValue(key, out value))
            return true;
        if (Packs.TryGetValue("en", out Dictionary<string, string>? english) && english.TryGetValue(key, out value))
            return true;
        return false;
    }

    private static Dictionary<string, string> Parse(string data)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (string raw in data.Split('\n'))
        {
            string line = raw.TrimEnd('\r');
            if (string.IsNullOrWhiteSpace(line)) continue;
            int separator = line.IndexOf('=');
            if (separator <= 0) continue;
            string key = line[..separator].Trim();
            string value = line[(separator + 1)..].Replace("\\n", "\r\n", StringComparison.Ordinal);
            result[key] = value;
        }
        return result;
    }

    private static void AddRelease21Completion()
    {
        foreach ((string code, string data) in CompletionPacks)
        {
            if (!Packs.TryGetValue(code, out Dictionary<string, string>? pack))
            {
                pack = new Dictionary<string, string>(StringComparer.Ordinal);
                Packs[code] = pack;
            }
            foreach ((string key, string value) in Parse(data))
                pack[key] = value;
        }
    }


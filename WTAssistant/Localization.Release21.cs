    // Final 2.1 release-completion pack.  These entries only replace an English
    // fallback (or a missing value), so the hand-tuned translations already in
    // the older per-language files remain authoritative.
    private static void AddRelease21Translations()
    {
        foreach ((string code, Dictionary<string, string> pack) in Release21Packs)
        {
            if (!SupplementalTexts.TryGetValue(code, out Dictionary<string, string>? target))
            {
                target = new Dictionary<string, string>(StringComparer.Ordinal);
                SupplementalTexts[code] = target;
            }

            foreach ((string key, string translated) in pack)
            {
                if (!Texts["en"].TryGetValue(key, out string? english))
                {
                    target[key] = translated;
                    continue;
                }

                string? current = null;
                if (target.TryGetValue(key, out string? supplemental)) current = supplemental;
                else if (Texts.TryGetValue(code, out Dictionary<string, string>? language) &&
                         language.TryGetValue(key, out string? value)) current = value;

                if (current is null || current == english ||
                    (string.IsNullOrWhiteSpace(current) && !string.IsNullOrWhiteSpace(english)))
                    target[key] = translated;
            }
        }
    }

    private static Dictionary<string, string> ParseRelease21Pack(string data)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (string raw in data.Split('\n'))
        {
            string line = raw.TrimEnd('\r');
            if (string.IsNullOrWhiteSpace(line) || line.StartsWith('#')) continue;
            int separator = line.IndexOf('=');
            if (separator <= 0) continue;
            string key = line[..separator].Trim();
            string value = line[(separator + 1)..]
                .Replace("\\n", "\r\n", StringComparison.Ordinal);
            result[key] = value;
        }
        return result;
    }

